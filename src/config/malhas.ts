function solid(name: string, color: string): FabricColor {
  return { name, hex: color };
}

function pattern(
  name: string,
  kind: Exclude<FabricPattern, "solid">,
  color: string,
  accent = "#F4F2EE",
  highlight?: string,
): FabricColor {
  return { name, hex: color, pattern: kind, accent, highlight };
}

function heather(name: string, base: string, dark: string, light: string): FabricColor {
  return pattern(name, "heather", base, dark, light);
}

function asHeather(color: FabricColor): FabricColor {
  if (color.pattern === "heather") return color;
  return { name: color.name, hex: color.hex, pattern: "heather" };
}

function applyMesclaHeather(categories: FabricCategory[]): FabricCategory[] {
  return categories.map((category) => ({
    ...category,
    colors: category.colors.map((color) => {
      const namedMescla = /mescla/i.test(color.name);
      const officeMescla =
        category.id === "office-mescla" && color.name !== "Branco";
      if (!namedMescla && !officeMescla) return color;
      return asHeather(color);
    }),
  }));
}

