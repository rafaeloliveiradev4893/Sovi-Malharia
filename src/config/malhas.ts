export function fabricColorCount(): number {
  return fabricCategories.reduce((total, category) => total + category.colors.length, 0);
}

export function findFabricColor(categoryId: string, name: string) {
  const category = fabricCategories.find((item) => item.id === categoryId);
  const color = category?.colors.find((item) => item.name === name);
  if (!category || !color) return undefined;
  return { category, color };
}

export function fabricMessage(category: string, color: string): string {
  if (category === "Fitas refletivas") {
    return `Olá! Vi o catálogo da Sovi e gostaria de orçamento da fita refletiva ${color} para aplicar na camisa.`;
  }
  return `Olá! Vi o catálogo de malhas da Sovi e gostaria de orçamento na ${category}, cor ${color}.`;
}
